import console from "node:console";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { dirname, resolve as resolvePath } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const defaultProjectRoot = resolvePath(scriptDirectory, "..");

const MODEL_FILES = ["geom.js", "vehicle.js"];
const GENERATED_PREFIX = "// @generated by scripts/sync-r2-model.mjs";

function generatedHeader(fileName) {
  return `${GENERATED_PREFIX}\n// Canonical source: public/garage/src/${fileName}\n// Do not edit this Configure mirror; edit the Garage source and run \`pnpm model:sync\`.\n\n`;
}

function renderMirror(fileName, source) {
  if (source.startsWith(GENERATED_PREFIX)) {
    throw new Error(
      `Refusing to mirror generated content from public/garage/src/${fileName}. ` +
        "The Garage file must remain the human-authored source.",
    );
  }

  return `${generatedHeader(fileName)}${source}`;
}

export function getCanonicalR2ModelPaths(projectRoot = defaultProjectRoot) {
  const root = resolvePath(projectRoot);
  return MODEL_FILES.map((fileName) => ({
    fileName,
    source: resolvePath(root, "public", "garage", "src", fileName),
    mirror: resolvePath(root, "src", "scene", "r2", fileName),
  }));
}

async function inspectCanonicalR2Model(projectRoot = defaultProjectRoot) {
  const entries = await Promise.all(
    getCanonicalR2ModelPaths(projectRoot).map(async (paths) => {
      const source = await readFile(paths.source, "utf8");
      const expected = renderMirror(paths.fileName, source);
      let actual = null;

      try {
        actual = await readFile(paths.mirror, "utf8");
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }

      return { ...paths, expected, current: actual === expected };
    }),
  );

  return entries;
}

export async function checkCanonicalR2Model(projectRoot = defaultProjectRoot) {
  const entries = await inspectCanonicalR2Model(projectRoot);
  const stale = entries.filter((entry) => !entry.current);

  if (stale.length > 0) {
    const error = new Error(
      `Configure's generated R2 mirror is stale: ${stale
        .map((entry) => entry.fileName)
        .join(", ")}. Run \`pnpm model:sync\`.`,
    );
    error.code = "R2_MODEL_MIRROR_STALE";
    error.files = stale.map((entry) => entry.fileName);
    throw error;
  }

  return {
    checked: entries.map((entry) => entry.fileName),
    canonicalDirectory: "public/garage/src",
    mirrorDirectory: "src/scene/r2",
  };
}

export async function syncCanonicalR2Model(projectRoot = defaultProjectRoot) {
  const entries = await inspectCanonicalR2Model(projectRoot);
  const stale = entries.filter((entry) => !entry.current);

  await Promise.all(
    stale.map(async (entry) => {
      await mkdir(dirname(entry.mirror), { recursive: true });
      const temporaryPath = `${entry.mirror}.tmp-${process.pid}`;
      await writeFile(temporaryPath, entry.expected, "utf8");
      await rename(temporaryPath, entry.mirror);
    }),
  );

  return {
    checked: entries.map((entry) => entry.fileName),
    updated: stale.map((entry) => entry.fileName),
    canonicalDirectory: "public/garage/src",
    mirrorDirectory: "src/scene/r2",
  };
}

async function runCli() {
  const args = process.argv.slice(2);
  const checkOnly = args.includes("--check");
  const unknown = args.filter((argument) => argument !== "--check");
  if (unknown.length > 0) throw new Error(`Unknown argument: ${unknown.join(", ")}`);

  if (checkOnly) {
    const result = await checkCanonicalR2Model();
    console.log(`R2 model mirror is current (${result.checked.join(", ")}).`);
    return;
  }

  const result = await syncCanonicalR2Model();
  const summary =
    result.updated.length > 0
      ? `updated ${result.updated.join(", ")}`
      : "already current";
  console.log(`Garage → Configure R2 model mirror: ${summary}.`);
}

const invokedPath = process.argv[1] ? resolvePath(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) {
  runCli().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
